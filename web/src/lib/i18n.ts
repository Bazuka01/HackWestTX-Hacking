export const MESSAGES: Record<LanguageCode, Messages> = { en, es, fr, hi, pt };

// Lowercase and drop accents for searching, so "mecanica" finds "Mecánica".
export function foldForSearch(text: string) {
  return text.normalize("NFD").replace(/\p{Diacritic}/gu, "").toLowerCase();
}

// Translated label for a stored English value; unknown values (like a
// custom major the student typed) are shown as they are.
export function labelFor(labels: Record<string, string>, value: string) {
  return labels[value] ?? value;
}

// Label for an organization tag, using the matching interest option.
export function tagLabel(messages: Messages, tag: string) {
  if (tag === "community") return messages.options.community;
  const interests: Record<string, string> = messages.options.interests;
  const option = Object.keys(interests).find((interest) => interestTag(interest) === tag);
  return option ? interests[option] : tag;
}
